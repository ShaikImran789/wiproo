SELECT EMPNO, ENAME, DEPTNO
FROM EMP
WHERE DEPTNO = (
    SELECT DEPTNO
    FROM EMP
    WHERE ENAME = 'SMITH'
);


SELECT EMPNO, ENAME, SAL
FROM EMP
WHERE SAL >
(
    SELECT AVG(SAL)
    FROM EMP
);




SELECT E1.ENAME, E1.JOB
FROM EMP E1
WHERE EXISTS
(
    SELECT *
    FROM EMP E2
    WHERE E2.EMPNO = E1.EMPNO
      AND E2.JOB = 'MANAGER'
);




SELECT EMPNO, ENAME, SAL
FROM EMP
WHERE SAL < ALL
(
    SELECT SAL
    FROM EMP
    WHERE DEPTNO = 10
);



SELECT EMPNO, ENAME, DEPTNO, MGR
FROM EMP
WHERE (DEPTNO, MGR) =
(
    SELECT DEPTNO, MGR
    FROM EMP
    WHERE ENAME = 'SMITH'
)
AND ENAME <> 'SMITH';


SELECT EMPNO, ENAME
FROM EMP
WHERE DEPTNO IN
(
    SELECT DISTINCT DEPTNO
    FROM EMP
    WHERE ENAME LIKE '%R%'
);



SELECT ENAME, DEPTNO, JOB
FROM EMP
WHERE DEPTNO =
(
    SELECT DEPTNO
    FROM DEPT
    WHERE LOC = 'NEW YORK'
);





SELECT ENAME, DEPTNO, JOB
FROM EMP
WHERE DEPTNO =
(
    SELECT DEPTNO
    FROM DEPT
    WHERE LOC = '&LOC'
);





SELECT ENAME, SAL
FROM EMP
WHERE MGR =
(
    SELECT EMPNO
    FROM EMP
    WHERE ENAME = 'KING'
);



SELECT EMPNO, ENAME, JOB, DEPTNO
FROM EMP
WHERE DEPTNO =
(
    SELECT DEPTNO
    FROM EMP
    WHERE ENAME = 'JAMES'
);


SELECT EMPNO, ENAME, SAL, DEPTNO
FROM EMP E
WHERE SAL <
(
    SELECT AVG(SAL)
    FROM EMP
    WHERE DEPTNO = E.DEPTNO
);




SELECT D.LOC,
(
    SELECT AVG(E.SAL)
    FROM EMP E
    WHERE E.DEPTNO = D.DEPTNO
) AS AVG_SAL
FROM DEPT D;



SELECT *
FROM
(
    SELECT EMPNO, ENAME, SAL
    FROM EMP
    ORDER BY SAL ASC
)
WHERE ROWNUM <= 3;




SELECT *
FROM
(
    SELECT *
    FROM EMP
    ORDER BY EMPNO DESC
)
WHERE ROWNUM <= 5;





